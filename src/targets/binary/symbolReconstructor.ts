import { open, stat } from "node:fs/promises";
import type { DataModel, ModelField } from "../../ir/types.js";
import { FlutterCodeGenerator } from "../../generators/flutterCodeGenerator.js";
import { IdentitySanitizer } from "../../core/identitySanitizer.js";

export interface ExtractedDartClass {
  name: string;
  library?: string;
  fields: { name: string; type: string }[];
  methods: string[];
}

/**
 * Reconstructs Dart source classes from binary symbols and strings embedded in AOT snapshots.
 */
export class SymbolReconstructor {
  private codeGen = new FlutterCodeGenerator();

  /**
   * Scans a libapp.so binary file to extract class names, methods, and fields.
   */
  public async extractClassesFromBinary(filePath: string): Promise<ExtractedDartClass[]> {
    const fileStat = await stat(filePath);
    const readSize = Math.min(Number(fileStat.size), 10 * 1024 * 1024);
    const buffer = Buffer.alloc(readSize);

    const fh = await open(filePath, "r");
    try {
      await fh.read(buffer, 0, readSize, 0);
    } finally {
      await fh.close();
    }

    const content = buffer.toString("utf-8");
    const classesMap = new Map<string, ExtractedDartClass>();

    // Detect Dart class signatures like package:app/.../class_name.dart or ClassName
    const classRegex = /package:[a-zA-Z0-9_\/]+\/([a-zA-Z0-9_]+)\.dart/g;
    let match: RegExpExecArray | null;

    while ((match = classRegex.exec(content)) !== null) {
      const rawName = match[1];
      const className = IdentitySanitizer.toPascalCase(rawName);
      if (className.length > 2 && !classesMap.has(className)) {
        classesMap.set(className, {
          name: className,
          library: match[0],
          fields: [],
          methods: [],
        });
      }
    }

    // Detect class-scoped method tokens (e.g. ClassName.methodName)
    const methodRegex = /([A-Z][a-zA-Z0-9_]{2,30})\.([a-z][a-zA-Z0-9_]{2,30})/g;
    let methodMatch: RegExpExecArray | null;
    while ((methodMatch = methodRegex.exec(content)) !== null) {
      const className = methodMatch[1];
      const methodName = methodMatch[2];
      const cls = classesMap.get(className);
      if (cls && !cls.methods.includes(methodName)) {
        cls.methods.push(methodName);
      }
    }

    return Array.from(classesMap.values());
  }

  /**
   * Synthesizes extracted binary class definitions into clean Dart source code.
   */
  public synthesizeDartFiles(
    extractedClasses: ExtractedDartClass[],
    options: { appName?: string; packageId?: string; sourceArtifactPath?: string } = {}
  ): Map<string, string> {
    const fileResults = new Map<string, string>();
    const identity = IdentitySanitizer.resolveIdentity({
      userAppName: options.appName,
      userPackageId: options.packageId,
      sourceArtifactPath: options.sourceArtifactPath,
    });

    for (const cls of extractedClasses) {
      const cleanName = IdentitySanitizer.sanitizeClassName(cls.name, identity);
      const dataModel: DataModel = {
        name: cleanName,
        fields: cls.fields.map((f) => ({
          name: f.name,
          dartType: f.type || "String",
          isNullable: true,
          isList: false,
        })),
      };

      const baseCode = this.codeGen.generateDataModel(dataModel);

      // Append recovered method stubs (excluding methods already generated by generateDataModel)
      const reservedMethods = new Set(["fromJson", "toJson", "toString", "hashCode", "noSuchMethod", cleanName]);
      const methodStubs = cls.methods
        .filter((m) => !reservedMethods.has(m) && /^[a-zA-Z_][a-zA-Z0-9_]*$/.test(m))
        .map((m) => `  void ${m}() {\n    // Recovered method signature\n  }\n`)
        .join("\n");

      const rawCode = baseCode.replace(
        /}\s*$/,
        `\n${methodStubs}}\n`
      );

      const finalCode = IdentitySanitizer.sanitizeCodeAndStrings(rawCode, identity);

      fileResults.set(`${IdentitySanitizer.toSnakeCase(cleanName)}.dart`, finalCode);
    }

    return fileResults;
  }
}
