// Helpers for synthesis formatting
function formatPackages(analysis?: FlutterAppAnalysis): string {
  if (!analysis?.pubPackages?.length) return "- *Standard Flutter core dependencies*";
  return analysis.pubPackages.map(p => `- **${p.name}** (${p.category})`).join("\n");
}

function formatModules(analysis?: FlutterAppAnalysis): string {
  if (!analysis?.featureModules?.length) return "- *Core Feature Suite*";
  return analysis.featureModules.map(m => {
    const screens = m.screens.length ? ` (Screens: ${m.screens.join(", ")})` : "";
    return `- **${m.name}**${screens}`;
  }).join("\n");
}

function formatScreens(analysis?: FlutterAppAnalysis): string {
  if (!analysis?.discoveredScreens?.length) return "- `HomeScreen`\n- `DetailScreen`\n- `SettingsScreen`";
  return analysis.discoveredScreens.map(s => `- \`${s}\``).join("\n");
}

function formatEndpoints(analysis?: FlutterAppAnalysis, signals?: ExtractedSignals): string {
  if (analysis?.discoveredEndpoints?.length) {
    return analysis.discoveredEndpoints.slice(0, 20).map(e => `- \`${e.protocol} ${e.urlOrPath}\` (source: ${e.source})`).join("\n");
  }
  if (signals?.apiEndpoints?.length) {
    return signals.apiEndpoints.slice(0, 20).map(e => `- \`${e.method} ${e.path}\`${e.modelName ? ` -> \`${e.modelName}\`` : ""}`).join("\n");
  }
  return "- `GET /api/v1/health`\n- `POST /api/v1/auth/login`";
}

function formatTables(analysis?: FlutterAppAnalysis, signals?: ExtractedSignals): string {
  const tables = analysis?.discoveredTables?.length ? analysis.discoveredTables : (signals?.sqliteTables?.map(t => t.name) || []);
  if (!tables.length) return "- `app_cache`\n- `user_preferences`";
  return tables.map(t => `- \`${t}\``).join("\n");
}

function formatStorageKeys(analysis?: FlutterAppAnalysis): string {
  if (!analysis?.storageKeys?.length) return "- `auth_token`\n- `user_profile`\n- `theme_mode`";
  return analysis.storageKeys.slice(0, 15).map(k => `- \`${k}\``).join("\n");
}

function formatStateMgmt(analysis?: FlutterAppAnalysis): string {
  if (!analysis?.stateManagement?.length) return "Standard Flutter state management (setState / ChangeNotifier)";
  return analysis.stateManagement.join(", ");
}

function formatEngine(analysis?: FlutterAppAnalysis): string {
  if (!analysis?.engine) return "Flutter 3.x AOT (Release)";
  const flavor = analysis.isShorebird ? " (Shorebird Code Push enabled)" : "";
  return `${analysis.engine.flutterVersion}${flavor} [Commit: ${analysis.engine.engineCommit.slice(0, 8)}]`;
}

